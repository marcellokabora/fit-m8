// Generates the client-side fallback photo pools from fake profiles in Firestore.
// Usage: npm run generate-fallback-photos
const admin = require('firebase-admin');
const { FieldPath, getFirestore } = require('firebase-admin/firestore');
const fs = require('fs');
const path = require('path');

const env = {};
fs.readFileSync(path.resolve(process.cwd(), '.env'), 'utf-8')
    .split('\n')
    .map(line => line.trim())
    .filter(line => line && !line.startsWith('#') && line.includes('='))
    .forEach(line => {
        const [key, ...rest] = line.split('=');
        env[key.trim()] = rest.join('=').trim();
    });

const serviceAccount = JSON.parse(
    fs.readFileSync(path.resolve(process.cwd(), 'firebase-key.json'), 'utf-8')
);

admin.initializeApp({
    credential: admin.cert(serviceAccount),
    projectId: env.PUBLIC_FIREBASE_PROJECT_ID
});

function shuffled(values) {
    const result = [...values];
    for (let index = result.length - 1; index > 0; index--) {
        const swapIndex = Math.floor(Math.random() * (index + 1));
        [result[index], result[swapIndex]] = [result[swapIndex], result[index]];
    }
    return result;
}

function normalizePhoto(value) {
    const url = new URL(value.trim());
    url.searchParams.delete('auto');
    url.searchParams.append('auto', 'format');
    url.hash = '';
    return url.toString();
}

function formatPool(name, urls) {
    return `export const ${name} = [\n${urls.map(url => `\t${JSON.stringify(url)}`).join(',\n')}\n] as const;`;
}

async function main() {
    const db = getFirestore();
    const snapshot = await db.collection('users')
        .where(FieldPath.documentId(), '>=', 'fake_')
        .where(FieldPath.documentId(), '<', 'fake_\uf8ff')
        .get();
    const pools = { female: new Set(), male: new Set() };

    for (const doc of snapshot.docs) {
        const data = doc.data();
        const photo = Array.isArray(data.photos) ? data.photos[0] : undefined;
        if (!(data.gender in pools) || typeof photo !== 'string' || !photo.trim()) continue;
        pools[data.gender].add(normalizePhoto(photo));
    }

    for (const [gender, urls] of Object.entries(pools)) {
        if (urls.size < 100) throw new Error(`Only ${urls.size} unique ${gender} photos are available`);
    }

    const femalePhotos = shuffled([...pools.female]).slice(0, 100);
    const malePhotos = shuffled([...pools.male]).slice(0, 100);
    const output = [
        '// Generated by scripts/generate-fallback-photos.cjs. Do not edit manually.',
        '',
        formatPool('FEMALE_FALLBACK_PHOTOS', femalePhotos),
        '',
        formatPool('MALE_FALLBACK_PHOTOS', malePhotos),
        ''
    ].join('\n');

    fs.writeFileSync(path.resolve(process.cwd(), 'src/lib/fallbackPhotos.generated.ts'), output);
    console.log(`Generated ${femalePhotos.length} female and ${malePhotos.length} male fallback photos.`);
}

main().catch(error => {
    console.error('Fallback photo generation failed:', error.message);
    process.exit(1);
});